import { defineConfig } from 'vite';
import react from '@vitejs/plugin-react';
import { fileURLToPath } from 'node:url';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { brotliCompressSync, gzipSync, constants as zlib } from 'node:zlib';

/**
 * Emit sw.js with the exact list of built files to precache, so the app,
 * worker, and WASM work offline after the first visit, at the configured base path.
 */
function serviceWorker() {
  let base;
  return {
    configResolved(config) {
      base = config.base;
      if (!base.startsWith('/') || base.startsWith('//') || !base.endsWith('/')) {
        throw new Error('Use an absolute pathname for base, such as / or /open-online-writer/.');
      }
    },
    name: 'online-writer-sw',
    apply: 'build',
    // Runs after Vite's HTML plugin, which drops the entry chunks of pages without
    // their own code; listing one of those would make the whole precache (and so the
    // service worker) fail to install.
    generateBundle: { order: 'post', handler(_options, bundle) {
      // The WebLLM chunk is only wanted by people who choose an in-browser model.
      const files = Object.keys(bundle).filter((f) => !f.endsWith('.map') && f !== 'sw.js' && !/webllm/u.test(f));
      const urls = [base, ...files.map((f) => `${base}${f}`), `${base}logo.png`, `${base}logo-512.png`, `${base}manifest.webmanifest`];
      const version = Date.now().toString(36);
      this.emitFile({
        type: 'asset',
        fileName: 'sw.js',
        source: `// Generated by vite.config.js. Only this installation's app files are cached.
const BASE = ${JSON.stringify(base)};
const PREFIX = 'open-writer:' + encodeURIComponent(BASE) + ':';
const CACHE = PREFIX + '${version}';
const URLS = ${JSON.stringify(urls)};
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(URLS)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith(PREFIX) && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});
self.addEventListener('fetch', (e) => {
  const url = new URL(e.request.url);
  if (e.request.method !== 'GET' || url.origin !== location.origin || !url.pathname.startsWith(BASE)) return;
  if (e.request.mode === 'navigate') {
    e.respondWith(fetch(e.request).catch(async () => {
      const cache = await caches.open(CACHE);
      const path = url.pathname.endsWith('/') ? url.pathname + 'index.html' : url.pathname;
      return (await cache.match(path, { ignoreVary: true })) || cache.match(BASE, { ignoreVary: true });
    }));
    return;
  }
  e.respondWith(caches.open(CACHE).then(async (cache) => (await cache.match(e.request, { ignoreVary: true })) || fetch(e.request)));
});
`,
      });
    } },
  };
}

/**
 * Write Brotli and gzip copies of large text and WebAssembly assets next to them. The
 * server sends a copy with its exact Content-Length; on-the-fly compression (Caddy) has
 * no length, and Chromium then fails to cache the 20 MB Harper WASM, which stops the
 * service worker from installing (no offline). Runs after the bundle is written, so the
 * copies are not in the precache list.
 */
function precompress() {
  return {
    name: 'online-writer-precompress',
    apply: 'build',
    writeBundle(options, bundle) {
      for (const file of Object.keys(bundle)) {
        if (!/\.(js|css|wasm|svg|json)$/u.test(file)) continue;
        const path = join(options.dir, file);
        const data = readFileSync(path);
        if (data.length < 1024) continue;
        writeFileSync(`${path}.br`, brotliCompressSync(data, { params: { [zlib.BROTLI_PARAM_QUALITY]: 9, [zlib.BROTLI_PARAM_SIZE_HINT]: data.length } }));
        writeFileSync(`${path}.gz`, gzipSync(data, { level: 9 }));
      }
    },
  };
}

// configure-pages supplies the deployment pathname; local builds default to /.
export default defineConfig({
  base: process.env.OW_BASE_PATH || '/',
  appType: 'mpa',
  plugins: [react(), serviceWorker(), precompress()],
  // harper.js locates its WASM with import.meta.url; pre-bundling would break that.
  optimizeDeps: { exclude: ['harper.js'] },
  worker: { format: 'es' },
  build: {
    target: 'es2022',
    sourcemap: true,
    chunkSizeWarningLimit: 4000,
    // The editor plus the landing and privacy pages (frontend/<page>/index.html).
    rollupOptions: {
      input: Object.fromEntries(
        ['index.html', 'privacy/index.html', 'grammar-checker/index.html', 'paraphrasing-tool/index.html', 'passive-voice-checker/index.html']
          .map((p) => [p.replace(/\/?index\.html$/u, '') || 'main', fileURLToPath(new URL(p, import.meta.url))]),
      ),
      output: {
        manualChunks(id) {
          if (id.includes('@mlc-ai/web-llm')) return 'webllm';
          return undefined;
        },
      },
    },
  },
});
